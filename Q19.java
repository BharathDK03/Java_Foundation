import java.util.*;

public class Q19 {
    public static void main(String[] args) {
        eo(3);
        eo(4);

    }

    public static void eo(int a) {
        if (a % 2 == 0) {
            System.out.println("the number is even");
        } else {
            System.out.println("the number is odd");
        }
    }

}
